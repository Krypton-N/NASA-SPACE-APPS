MODELS_BY_ID = {m["id"]: m for m in BEDROCK_MODELS}

# Proveedores únicos
PROVIDERS = sorted(list(set(m["provider"] for m in BEDROCK_MODELS)))

# Categorías únicas
CATEGORIES = sorted(list(set(m["category"] for m in BEDROCK_MODELS)))

# Modelo por defecto
DEFAULT_MODEL_ID = "us.anthropic.claude-sonnet-4-6"
FALLBACK_MODEL_ID = "google.gemma-3-12b-it"


def get_model(model_id: str):
    """Retorna los metadatos de un modelo por su ID o None si no existe."""
    return MODELS_BY_ID.get(model_id)


def get_verified_models():
    """Retorna la lista de modelos verificados y listos para inferencia en Bedrock."""
    return [m for m in BEDROCK_MODELS if m.get("is_verified")]


def get_models_by_provider(provider_name: str):
    """Filtra modelos por proveedor."""
    return [m for m in BEDROCK_MODELS if m["provider"].lower() == provider_name.lower()]


def get_catalog_summary():
    """Genera un resumen estructurado del catálogo de Bedrock."""
    return {
        "total_models": len(BEDROCK_MODELS),
        "verified_models": len(get_verified_models()),
        "providers": PROVIDERS,
        "categories": CATEGORIES,
        "default_model": DEFAULT_MODEL_ID,
        "models": BEDROCK_MODELS,
    }
